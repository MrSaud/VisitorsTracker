"""Build something double-clickable around the existing server.

On macOS that is VisitorsTracker.app. The bundle is not cosmetic: macOS
attributes camera access to an application, and a script run from a shell
is not one. Permission lands on whatever launched it -- Terminal, an
editor, a coding agent -- and an app that is not in Privacy & Security >
Camera cannot be added to it, because that pane has no "+" button. A bundle
has an identity, so it appears there by name and keeps its answer.

On Windows that is VisitorsTracker.bat plus a shortcut carrying the icon.
Windows needs none of the identity machinery -- its camera permission is a
system-wide toggle for desktop apps rather than a per-application grant --
so the launcher only has to start the right interpreter without leaving a
console window on screen.
"""

from __future__ import annotations

import plistlib
import shutil
import stat
import subprocess
import sys
from pathlib import Path

from django.conf import settings
from django.core.management.base import BaseCommand, CommandError

APP_NAME = "VisitorsTracker"
BUNDLE_ID = "com.visitorstracker.desktop"
VERSION = "1.0"

# Used unless --icon says otherwise. Regenerate both from new artwork with
# scripts/make_icon.py, which shapes each one the way its platform wants.
DEFAULT_ICONS = {
    "macos": Path("assets") / "AppIcon.icns",
    "windows": Path("assets") / "AppIcon.ico",
}
DEFAULT_ICON = DEFAULT_ICONS["macos"]       # kept for the macOS path

# Shown by macOS in the permission prompt and in Privacy & Security.
CAMERA_REASON = (
    "VisitorsTracker counts people crossing a line in the camera's view. "
    "Video is processed on this machine and is not recorded or uploaded."
)


def info_plist(app_name=APP_NAME, bundle_id=BUNDLE_ID, version=VERSION,
               icon=None) -> dict:
    """The bundle's Info.plist.

    NSCameraUsageDescription is not optional: without it macOS terminates
    the process the moment it touches the camera, rather than prompting.
    """
    plist = {
        "CFBundleName": app_name,
        "CFBundleDisplayName": app_name,
        "CFBundleIdentifier": bundle_id,
        "CFBundleExecutable": app_name,
        "CFBundlePackageType": "APPL",
        "CFBundleInfoDictionaryVersion": "6.0",
        "CFBundleShortVersionString": version,
        "CFBundleVersion": version,
        "LSMinimumSystemVersion": "11.0",
        "NSHighResolutionCapable": True,
        "NSCameraUsageDescription": CAMERA_REASON,
        # The window is the interface; no need for a document-based app.
        "LSApplicationCategoryType": "public.app-category.utilities",
    }
    if icon:
        plist["CFBundleIconFile"] = Path(icon).name
    return plist


def launcher_script(project_dir, python_path) -> str:
    """The bundle's main executable.

    The path to the project is baked in rather than guessed from the
    bundle's own location, so the app still works after being dragged to
    the Dock or to /Applications. Move the project and rebuild.
    """
    return f"""#!/bin/sh
# Generated by `manage.py build_app`. Do not edit; rebuild instead.
set -e
cd {shell_quote(str(project_dir))}
exec {shell_quote(str(python_path))} -m counter.desktop
"""


def shell_quote(value) -> str:
    return "'" + str(value).replace("'", "'\\''") + "'"


def this_platform() -> str:
    return "windows" if sys.platform.startswith("win") else "macos"


def windows_launcher_script(project_dir, python_path) -> str:
    """The .bat the shortcut points at.

    ``pythonw.exe`` rather than ``python.exe``: the console host would
    otherwise sit behind the window for as long as the app runs, and
    closing it would kill the server. ``start ""`` lets the batch file
    return immediately instead of blocking until the app exits.
    """
    return (
        "@echo off\r\n"
        "rem Generated by `manage.py build_app`. Do not edit; rebuild instead.\r\n"
        f'cd /d "{project_dir}"\r\n'
        f'start "" "{python_path}" -m counter.desktop\r\n'
    )


def windows_service_script(project_dir, python_path) -> str:
    """Headless: the server and the cameras, no window.

    This is what Task Scheduler runs. The environment variables have to be
    set here because a scheduled task's <Exec> has nowhere to put them, and
    without COUNTER_AUTOSTART the server starts but no camera does.
    """
    return (
        "@echo off\r\n"
        "rem Generated by `manage.py build_app`. Do not edit; rebuild instead.\r\n"
        "rem Headless counting for Task Scheduler. No window.\r\n"
        "set COUNTER_AUTOSTART=1\r\n"
        "set COUNTER_RECONNECT_ATTEMPTS=0\r\n"
        "set DJANGO_DEBUG=0\r\n"
        "set DJANGO_ALLOWED_HOSTS=127.0.0.1,localhost\r\n"
        f'set DJANGO_SECRET_KEY_FILE={project_dir}\\.secret_key\r\n'
        "rem Set these for alerting.\r\n"
        "rem set COUNTER_ALERTS_ENABLED=1\r\n"
        "rem set COUNTER_ALERT_WEBHOOK=https://...\r\n"
        f'cd /d "{project_dir}"\r\n'
        f'"{python_path}" manage.py runserver 127.0.0.1:8000 --noreload\r\n'
    )


def shortcut_script(shortcut, target, icon, working_dir) -> str:
    """PowerShell that creates the .lnk, because a .bat cannot carry an icon."""
    lines = [
        "# Generated by `manage.py build_app`. Do not edit; rebuild instead.",
        "$shell = New-Object -ComObject WScript.Shell",
        f'$link = $shell.CreateShortcut("{shortcut}")',
        f'$link.TargetPath = "{target}"',
        f'$link.WorkingDirectory = "{working_dir}"',
        f'$link.Description = "{APP_NAME}"',
    ]
    if icon:
        lines.append(f'$link.IconLocation = "{icon}"')
    lines += ["$link.Save()", f'Write-Host "Created {shortcut}"']
    return "\r\n".join(lines) + "\r\n"


class Command(BaseCommand):
    help = "Build a double-clickable launcher for this platform."

    def add_arguments(self, parser):
        parser.add_argument(
            "--target", choices=("auto", "macos", "windows"), default="auto",
            help="Which launcher to build (default: whatever this machine is). "
                 "Naming one explicitly generates the files without running "
                 "the platform's own tools.")
        parser.add_argument(
            "--output", default=None,
            help="Where to put the bundle (default: dist/ in the project).")
        parser.add_argument(
            "--python", default=None,
            help="Interpreter the app runs (default: this project's .venv).")
        parser.add_argument(
            "--icon", default=None,
            help=f"An .icns file (default: {DEFAULT_ICON} when it exists).")
        parser.add_argument(
            "--no-icon", action="store_true",
            help="Build without an icon even if the default one is there.")
        parser.add_argument(
            "--no-sign", action="store_true",
            help="Skip the ad-hoc signature. The app still runs, but macOS "
                 "may forget its camera answer between rebuilds.")

    def handle(self, *args, **options):
        project_dir = Path(settings.BASE_DIR).resolve()
        target = options["target"]
        if target == "auto":
            target = "windows" if sys.platform.startswith("win") else "macos"

        python_path = Path(options["python"] or self.default_python(
            project_dir, target))
        # Only insist the interpreter exists when it is this machine's to
        # check: cross-generating the Windows files on a Mac cannot.
        if target == this_platform() and not python_path.exists():
            raise CommandError(f"No interpreter at {python_path}. Pass --python.")

        output = Path(options["output"] or project_dir / "dist").resolve()

        icon = options["icon"]
        if icon:
            icon = Path(icon).resolve()
            if not icon.exists():
                raise CommandError(f"No icon at {icon}.")
        elif not options["no_icon"]:
            # The project's own icon, when it has one. An explicit --icon
            # still wins, and a missing default is not an error.
            default = project_dir / DEFAULT_ICONS[target]
            icon = default if default.exists() else None

        if target != this_platform():
            # The paths baked into the launcher come from this machine, so
            # what comes out is readable but not runnable anywhere.
            self.stderr.write(self.style.WARNING(
                f"Generating a {target} launcher on {sys.platform}: the paths "
                f"in it are this machine's, so it is for inspection only. "
                f"Build it on the {target} machine to get a working one."))

        if target == "windows":
            return self.build_windows(project_dir, python_path, output, icon)
        return self.build_macos(project_dir, python_path, output, icon,
                                sign=not options["no_sign"])

    @staticmethod
    def default_python(project_dir, target):
        if target == "windows":
            # pythonw keeps the console window off the screen.
            return project_dir / ".venv" / "Scripts" / "pythonw.exe"
        return project_dir / ".venv" / "bin" / "python"

    # -- windows ----------------------------------------------------------

    def build_windows(self, project_dir, python_path, output, icon):
        output.mkdir(parents=True, exist_ok=True)
        launcher = output / f"{APP_NAME}.bat"
        service = output / f"{APP_NAME}-headless.bat"
        shortcut = output / f"{APP_NAME}.lnk"
        maker = output / "CreateShortcut.ps1"

        launcher.write_text(
            windows_launcher_script(project_dir, python_path), newline="")
        maker.write_text(
            shortcut_script(shortcut, launcher, icon, project_dir), newline="")
        # Task Scheduler needs a target that sets COUNTER_AUTOSTART; its
        # <Exec> has nowhere to put environment variables.
        service.write_text(
            windows_service_script(
                project_dir,
                str(python_path).replace("pythonw.exe", "python.exe")),
            newline="")

        made = False
        if sys.platform.startswith("win"):
            made = self.run_powershell(maker)

        self.stdout.write(self.style.SUCCESS(f"Built {launcher}"))
        self.stdout.write(f"  interpreter: {python_path}")
        self.stdout.write(f"  project:     {project_dir}")
        self.stdout.write(f"  icon:        {icon.name if icon else 'none'}")
        self.stdout.write(f"  shortcut:    {'created' if made else 'not created'}")
        self.stdout.write(f"  headless:    {service.name} (for Task Scheduler)")
        if made:
            self.stdout.write(
                f"\nDrag {shortcut.name} to the desktop or taskbar. Windows "
                "asks for camera access the first time, or allow desktop apps "
                "under Settings > Privacy & security > Camera.")
        else:
            self.stdout.write(
                f"\nOn the Windows machine, run:\n"
                f"  powershell -ExecutionPolicy Bypass -File {maker.name}\n"
                f"which creates {shortcut.name} with the icon attached.")

    def run_powershell(self, script) -> bool:
        try:
            result = subprocess.run(
                ["powershell", "-ExecutionPolicy", "Bypass", "-File", str(script)],
                capture_output=True, text=True, timeout=120)
        except (OSError, subprocess.SubprocessError) as error:
            self.stderr.write(f"powershell unavailable ({error}).")
            return False
        if result.returncode != 0:
            self.stderr.write(
                f"shortcut failed: {result.stderr.strip() or result.returncode}")
            return False
        return True

    # -- macos ------------------------------------------------------------

    def build_macos(self, project_dir, python_path, output, icon, sign=True):
        bundle = output / f"{APP_NAME}.app"
        contents = bundle / "Contents"
        macos = contents / "MacOS"
        resources = contents / "Resources"

        if bundle.exists():
            shutil.rmtree(bundle)
        macos.mkdir(parents=True)
        resources.mkdir(parents=True)

        with open(contents / "Info.plist", "wb") as handle:
            plistlib.dump(info_plist(icon=icon), handle)

        executable = macos / APP_NAME
        executable.write_text(launcher_script(project_dir, python_path))
        executable.chmod(executable.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP
                         | stat.S_IXOTH)

        if icon:
            shutil.copy2(icon, resources / icon.name)

        signed = self._sign(bundle) if sign else False

        self.stdout.write(self.style.SUCCESS(f"Built {bundle}"))
        self.stdout.write(f"  interpreter: {python_path}")
        self.stdout.write(f"  project:     {project_dir}")
        self.stdout.write(f"  signed:      {'ad-hoc' if signed else 'no'}")
        self.stdout.write(f"  icon:        {icon.name if icon else 'none'}")
        self.stdout.write(
            "\nOpen it once and allow camera access when macOS asks. It then "
            f"appears in Privacy & Security > Camera as {APP_NAME}.")

    def _sign(self, bundle) -> bool:
        """Ad-hoc signature, so TCC has a stable identity to remember."""
        try:
            result = subprocess.run(
                ["codesign", "--force", "--sign", "-",
                 "--identifier", BUNDLE_ID, str(bundle)],
                capture_output=True, text=True, timeout=120)
        except (OSError, subprocess.SubprocessError) as error:
            self.stderr.write(f"codesign unavailable ({error}); left unsigned.")
            return False
        if result.returncode != 0:
            self.stderr.write(
                f"codesign failed: {result.stderr.strip() or result.returncode}")
            return False
        return True
