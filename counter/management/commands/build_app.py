"""Build VisitorsTracker.app, a macOS bundle around the existing server.

Why a bundle at all: macOS attributes camera access to an application, and
a script run from a shell is not one. Permission lands on whatever launched
it -- Terminal, an editor, a coding agent -- and an app that is not in
Privacy & Security > Camera cannot be added to it, because that pane has no
"+" button. A bundle has an identity, so it appears there by name and keeps
its answer.
"""

from __future__ import annotations

import plistlib
import shutil
import stat
import subprocess
from pathlib import Path

from django.conf import settings
from django.core.management.base import BaseCommand, CommandError

APP_NAME = "VisitorsTracker"
BUNDLE_ID = "com.visitorstracker.desktop"
VERSION = "1.0"

# Shown by macOS in the permission prompt and in Privacy & Security.
CAMERA_REASON = (
    "VisitorsTracker counts people crossing a line in the camera's view. "
    "Video is processed on this machine and is not recorded or uploaded."
)


def info_plist(app_name=APP_NAME, bundle_id=BUNDLE_ID, version=VERSION,
               icon=None) -> dict:
    """The bundle's Info.plist.

    NSCameraUsageDescription is not optional: without it macOS terminates
    the process the moment it touches the camera, rather than prompting.
    """
    plist = {
        "CFBundleName": app_name,
        "CFBundleDisplayName": app_name,
        "CFBundleIdentifier": bundle_id,
        "CFBundleExecutable": app_name,
        "CFBundlePackageType": "APPL",
        "CFBundleInfoDictionaryVersion": "6.0",
        "CFBundleShortVersionString": version,
        "CFBundleVersion": version,
        "LSMinimumSystemVersion": "11.0",
        "NSHighResolutionCapable": True,
        "NSCameraUsageDescription": CAMERA_REASON,
        # The window is the interface; no need for a document-based app.
        "LSApplicationCategoryType": "public.app-category.utilities",
    }
    if icon:
        plist["CFBundleIconFile"] = Path(icon).name
    return plist


def launcher_script(project_dir, python_path) -> str:
    """The bundle's main executable.

    The path to the project is baked in rather than guessed from the
    bundle's own location, so the app still works after being dragged to
    the Dock or to /Applications. Move the project and rebuild.
    """
    return f"""#!/bin/sh
# Generated by `manage.py build_app`. Do not edit; rebuild instead.
set -e
cd {shell_quote(str(project_dir))}
exec {shell_quote(str(python_path))} -m counter.desktop
"""


def shell_quote(value) -> str:
    return "'" + str(value).replace("'", "'\\''") + "'"


class Command(BaseCommand):
    help = "Build VisitorsTracker.app so the app owns its camera permission."

    def add_arguments(self, parser):
        parser.add_argument(
            "--output", default=None,
            help="Where to put the bundle (default: dist/ in the project).")
        parser.add_argument(
            "--python", default=None,
            help="Interpreter the app runs (default: this project's .venv).")
        parser.add_argument(
            "--icon", default=None, help="An .icns file for the bundle.")
        parser.add_argument(
            "--no-sign", action="store_true",
            help="Skip the ad-hoc signature. The app still runs, but macOS "
                 "may forget its camera answer between rebuilds.")

    def handle(self, *args, **options):
        project_dir = Path(settings.BASE_DIR).resolve()
        python_path = Path(options["python"] or project_dir / ".venv" / "bin" / "python")
        if not python_path.exists():
            raise CommandError(f"No interpreter at {python_path}. Pass --python.")

        output = Path(options["output"] or project_dir / "dist").resolve()
        bundle = output / f"{APP_NAME}.app"
        contents = bundle / "Contents"
        macos = contents / "MacOS"
        resources = contents / "Resources"

        icon = options["icon"]
        if icon:
            icon = Path(icon).resolve()
            if not icon.exists():
                raise CommandError(f"No icon at {icon}.")

        if bundle.exists():
            shutil.rmtree(bundle)
        macos.mkdir(parents=True)
        resources.mkdir(parents=True)

        with open(contents / "Info.plist", "wb") as handle:
            plistlib.dump(info_plist(icon=icon), handle)

        executable = macos / APP_NAME
        executable.write_text(launcher_script(project_dir, python_path))
        executable.chmod(executable.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP
                         | stat.S_IXOTH)

        if icon:
            shutil.copy2(icon, resources / icon.name)

        signed = False
        if not options["no_sign"]:
            signed = self._sign(bundle)

        self.stdout.write(self.style.SUCCESS(f"Built {bundle}"))
        self.stdout.write(f"  interpreter: {python_path}")
        self.stdout.write(f"  project:     {project_dir}")
        self.stdout.write(f"  signed:      {'ad-hoc' if signed else 'no'}")
        self.stdout.write(
            "\nOpen it once and allow camera access when macOS asks. It then "
            f"appears in Privacy & Security > Camera as {APP_NAME}.")

    def _sign(self, bundle) -> bool:
        """Ad-hoc signature, so TCC has a stable identity to remember."""
        try:
            result = subprocess.run(
                ["codesign", "--force", "--sign", "-",
                 "--identifier", BUNDLE_ID, str(bundle)],
                capture_output=True, text=True, timeout=120)
        except (OSError, subprocess.SubprocessError) as error:
            self.stderr.write(f"codesign unavailable ({error}); left unsigned.")
            return False
        if result.returncode != 0:
            self.stderr.write(
                f"codesign failed: {result.stderr.strip() or result.returncode}")
            return False
        return True
